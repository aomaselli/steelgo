export function translateAuth(text: string | undefined, language: Language): string {
  if (!text) return "";
  if (language === "pt") return text;
  return COPY[text]?.[language === "en" ? 0 : 1] ?? text;
}

export function useAuthCopy() {
  const { language } = useLanguage();
  useEffect(() => { document.documentElement.lang = language === "pt" ? "pt-BR" : language; }, [language]);
  return useCallback((text: string | undefined) => translateAuth(text, language), [language]);
}

